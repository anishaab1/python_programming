#add, insert , remove and sort
num=[10,20,30]
num.append(40) #adding any no at the end of the list 
print(num)
print() #next line 
num.insert(1,15) #inserting any no at the specified index
print(num)
print()
num.remove(20) #helps to remove the specified element from the list
print(num)
print()
num.sort()#helps to sort the list in ascending order
print(num)
